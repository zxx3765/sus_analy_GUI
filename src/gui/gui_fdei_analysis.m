function onDiscoverResults(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
outputDir = handles.fdei.config.outputDir;
files = dir(fullfile(outputDir, 'FDEI_batch_runs*.mat'));
fileNames = arrayfun(@(item) fullfile(item.folder, item.name), files, ...
    'UniformOutput', false);
if isempty(fileNames)
    set(handles.fdei.plotUi.sourceFileList, 'String', fileNames, 'Value', []);
else
    set(handles.fdei.plotUi.sourceFileList, 'String', fileNames, ...
        'Value', 1:numel(fileNames));
end
set(handles.fdei.plotUi.statusText, 'String', sprintf('自动发现 %d 个文件。', numel(fileNames)));
set(figHandle, 'UserData', handles);
end

function onRunAnalysis(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
files = get(handles.fdei.plotUi.sourceFileList, 'String');
if ischar(files)
    files = {files};
end
if isempty(files)
    set(handles.fdei.plotUi.statusText, 'String', '请先选择 MAT 文件。');
    return;
end
try
    analysisCfg = fdei_config_utils('readanalysis', handles.fdei.plotUi, ...
        handles.fdei.config);
    [runs, ~, ~, ~] = fdei_load_batch_results(files, analysisCfg);
    [results, summary, context] = fdei_analyze_runs(runs, analysisCfg);
    handles.fdei.config = context.cfg;
    handles.fdei.lastResults = results;
    handles.fdei.lastSummary = summary;
    setTableFromTable(handles.fdei.plotUi.resultTable, results);
    setTableFromTable(handles.fdei.plotUi.summaryTable, summary);
    set(handles.fdei.plotUi.statusText, 'String', ...
        sprintf('分析完成：%d 条 runs。', height(results)));
catch exception
    set(handles.fdei.plotUi.statusText, 'String', ['分析错误：' exception.message]);
end
set(figHandle, 'UserData', handles);
end

