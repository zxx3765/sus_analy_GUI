function showFigure(src, figureIndex)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
if isempty(handles.fdei.lastResults)
    set(handles.fdei.plotUi.statusText, 'String', '请先运行分析。');
    return;
end
plotCfg = handles.fdei.config;
plotCfg.saveFigures = false;
allFigures = fdei_plot_figures12(handles.fdei.lastResults, plotCfg, ...
    'Visible', 'off');
keepFigure = allFigures{figureIndex};
set(keepFigure, 'Visible', 'on');
otherFigure = allFigures{3-figureIndex};
if isgraphics(otherFigure)
    delete(otherFigure);
end
handles.fdei.lastFigures = {keepFigure};
set(figHandle, 'UserData', handles);
set(handles.fdei.plotUi.statusText, 'String', sprintf('图%d 已打开。', figureIndex));
end

function onExportResults(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
if isempty(handles.fdei.lastResults)
    set(handles.fdei.plotUi.statusText, 'String', '请先运行分析。');
    return;
end
[fileName, filePath] = uiputfile('FDEI_analysis_results.mat', '保存分析结果');
if isequal(fileName, 0)
    return;
end
results = handles.fdei.lastResults; %#ok<NASGU>
summary = handles.fdei.lastSummary; %#ok<NASGU>
save(fullfile(filePath, fileName), 'results', 'summary', '-v7.3');
[folder, base] = fileparts(fullfile(filePath, fileName));
writetable(results, fullfile(folder, [base '_per_run.csv']));
writetable(summary, fullfile(folder, [base '_summary.csv']));
set(handles.fdei.plotUi.statusText, 'String', ['已导出：' fullfile(filePath, fileName)]);
end
end

