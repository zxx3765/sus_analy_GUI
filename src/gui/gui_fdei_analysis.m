function onBrowseModel(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
modelValue = char(string(get(handles.fdei.batchUi.modelEdit, 'String')));
startLocation = pwd;
if ismember(exist(modelValue, 'file'), [2 4])
    startLocation = modelValue;
elseif exist(fileparts(modelValue), 'dir') == 7
    startLocation = fileparts(modelValue);
end
[fileName, folder] = uigetfile( ...
    {'*.slx;*.mdl', 'Simulink 模型 (*.slx, *.mdl)'; '*.*', '所有文件'}, ...
    '选择 FDEI Simulink 模型', startLocation);
if isequal(fileName, 0)
    return;
end
modelFile = fullfile(folder, fileName);
set(handles.fdei.batchUi.modelEdit, 'String', modelFile);
handles.fdei.config.model = modelFile;
set(handles.fdei.batchUi.statusText, 'String', ['已选择模型：' modelFile]);
set(figHandle, 'UserData', handles);
end

function onBrowseOutputDir(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
