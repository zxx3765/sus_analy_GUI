end

function onExportConfig(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
try
    exportCfg = fdei_config_utils('readbatchdraft', ...
        handles.fdei.batchUi, handles.fdei.config);
    exportCfg = fdei_config_utils('readanalysis', ...
        handles.fdei.plotUi, exportCfg);
catch exception
    set(handles.fdei.batchUi.statusText, 'String', ...
        ['无法导出配置：' exception.message]);
    return;
end
[fileName, folder] = uiputfile('*.mat', '导出 FDEI 配置', ...
    fullfile(pwd, 'FDEI_config.mat'));
if isequal(fileName, 0)
    return;
end
try
    savedFile = fdei_save_config(fullfile(folder, fileName), exportCfg);
    handles.fdei.config = exportCfg;
    set(handles.fdei.batchUi.statusText, 'String', ['配置已导出：' savedFile]);
    appendLog(figHandle, ['FDEI 配置已导出：' savedFile]);
    set(figHandle, 'UserData', handles);
catch exception
    set(handles.fdei.batchUi.statusText, 'String', ...
        ['配置导出失败：' exception.message]);
end
end

function onImportConfig(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
[fileName, folder] = uigetfile('*.mat', '导入 FDEI 配置');
if isequal(fileName, 0)
    return;
end
oldCfg = handles.fdei.config;
try
    importedCfg = fdei_load_config(fullfile(folder, fileName), oldCfg);
    fdei_config_utils('applybatch', handles.fdei.batchUi, importedCfg);
    fdei_config_utils('applyanalysis', handles.fdei.plotUi, importedCfg);
catch exception
    fdei_config_utils('applybatch', handles.fdei.batchUi, oldCfg);
    fdei_config_utils('applyanalysis', handles.fdei.plotUi, oldCfg);
    set(handles.fdei.batchUi.statusText, 'String', ...
        ['配置导入失败：' exception.message]);
    return;
end
handles.fdei.config = importedCfg;
configFile = fullfile(folder, fileName);
set(handles.fdei.batchUi.statusText, 'String', ['配置已导入：' configFile]);
set(handles.fdei.plotUi.statusText, 'String', '分析参数已从配置文件更新。');
appendLog(figHandle, ['FDEI 配置已导入：' configFile]);
set(figHandle, 'UserData', handles);
end

function onEditSignalMapping(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
currentCfg = handles.fdei.config;
prompts = { ...
    '参数工作区（model/base）'; ...
    '信号来源（logsout/simulationoutput）'; ...
    'logsout 变量'; ...
    '时间变量'; ...
    'vs（簧载速度）'; ...
    'as（簧载加速度）'; ...
    'vd（相对速度，可与 vu 二选一）'; ...
    'vu（非簧载速度，可与 vd 二选一）'; ...
    'Fd（总阻尼力，可与 cCmd 二选一）'; ...
    'cCmd（控制阻尼，可与 Fd 二选一）'; ...
    'xr（路面位移，可选）'; ...
    'xu（非簧载位移，可选）'; ...
    'tireDef（轮胎挠度，可选）'; ...
    'suspDef（悬架挠度，可选）'; ...
    '手工工况：频率,幅值；频率,幅值'};
defaults = {currentCfg.parameterWorkspace; currentCfg.signalSource; ...
    currentCfg.logsoutVariable; currentCfg.timeVariable; ...
    currentCfg.signal.vs; currentCfg.signal.as; currentCfg.signal.vd; ...
    currentCfg.signal.vu; currentCfg.signal.Fd; currentCfg.signal.cCmd; ...
    currentCfg.signal.xr; currentCfg.signal.xu; currentCfg.signal.tireDef; ...
    currentCfg.signal.suspDef; formatManualCases(currentCfg.manualSineCases)};
answers = inputdlg(prompts, 'FDEI 信号映射与手工扫频工况', ...
    repmat([1 72], numel(prompts), 1), defaults);
if isempty(answers)
    return;
end
try
    currentCfg.parameterWorkspace = strtrim(answers{1});
    currentCfg.signalSource = strtrim(answers{2});
    currentCfg.logsoutVariable = strtrim(answers{3});
    currentCfg.timeVariable = strtrim(answers{4});
    signalNames = {'vs','as','vd','vu','Fd','cCmd','xr','xu','tireDef','suspDef'};
    for signalIndex = 1:numel(signalNames)
        currentCfg.signal.(signalNames{signalIndex}) = ...
            strtrim(answers{signalIndex+4});
    end
    currentCfg.manualSineCases = fdei_config_utils( ...
        'parsemanualcases', answers{15});
catch exception
    set(handles.fdei.batchUi.statusText, 'String', ...
        ['信号映射未保存：' exception.message]);
    return;
end
handles.fdei.config = currentCfg;
set(handles.fdei.batchUi.statusText, 'String', ...
    '信号映射已保存；运行前请执行“检查配置”。');
set(figHandle, 'UserData', handles);
end

function onValidateBatch(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
try
    batchCfg = fdei_config_utils('readbatch', handles.fdei.batchUi, handles.fdei.config);
    handles.fdei.config = batchCfg;
    set(handles.fdei.batchUi.statusText, 'String', '配置检查通过。');
    appendLog(figHandle, 'FDEI 批量配置检查通过。');
catch exception
    set(handles.fdei.batchUi.statusText, 'String', ['配置错误：' exception.message]);
    appendLog(figHandle, ['配置错误：' exception.message]);
end
set(figHandle, 'UserData', handles);
end

function onRunBatch(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
if handles.fdei.isRunning
    return;
end
try
    batchCfg = fdei_config_utils('readbatch', handles.fdei.batchUi, handles.fdei.config);
catch exception
    appendLog(figHandle, ['无法开始：' exception.message]);
    return;
end
handles.fdei.config = batchCfg;
handles.fdei.isRunning = true;
handles.fdei.stopRequested = false;
fdei_config_utils('updateprogress', handles.fdei.batchUi, 0, 0, '正在准备...');
set(handles.fdei.batchUi.runButton, 'Enable', 'off');
set(handles.fdei.batchUi.stopButton, 'Enable', 'on');
set(figHandle, 'UserData', handles);
try
    [~, ~, files] = fdei_run_batch(batchCfg, ...
        'ProgressFcn', @(done,total,row) batchProgress(figHandle,done,total,row), ...
        'LogFcn', @(message) appendLog(figHandle,message), ...
        'StopFcn', @(done,total) batchStopRequested(figHandle,done,total));
    appendLog(figHandle, ['批量结果已保存：' files.mat]);
catch exception
    appendLog(figHandle, ['批量仿真结束：' exception.message]);
end
handles = latestHandles(figHandle);
handles.fdei.isRunning = false;
set(handles.fdei.batchUi.runButton, 'Enable', 'on');
set(handles.fdei.batchUi.stopButton, 'Enable', 'off');
set(figHandle, 'UserData', handles);
end

function onStopBatch(src, ~)
figHandle = ancestor(src, 'figure');
handles = latestHandles(figHandle);
handles.fdei.stopRequested = true;
set(figHandle, 'UserData', handles);
appendLog(figHandle, '已请求在下一个工况边界停止。');
end

function batchProgress(figHandle, done, total, row)
handles = latestHandles(figHandle);
fdei_config_utils('updateprogress', handles.fdei.batchUi, ...
    done, total, row.Status);
drawnow;
end

function value = batchStopRequested(figHandle, ~, ~)
handles = latestHandles(figHandle);
value = handles.fdei.stopRequested;
drawnow;
end
end

