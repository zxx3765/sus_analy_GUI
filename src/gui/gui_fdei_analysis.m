function appendLog(fig, message)
handles = latestHandles(fig);
if ~isfield(handles, 'fdei') || ~ishandle(handles.fdei.batchUi.executionLogText)
    fprintf('[FDEI] %s\n', message);
    return;
end
control = handles.fdei.batchUi.executionLogText;
current = get(control, 'String');
if isempty(current)
    lines = {char(string(message))};
elseif ischar(current)
    lines = {current; char(string(message))};
else
    lines = [current; {char(string(message))}];
end
if numel(lines) > 100
    lines = lines(end-99:end);
end
set(control, 'String', lines, 'Value', numel(lines));
drawnow;
end

function setTableFromTable(control, value)
if isempty(value)
    set(control, 'Data', {});
    return;
end
set(control, 'Data', table2cell(value), 'ColumnName', value.Properties.VariableNames);
end

function value = joinNumbers(numbers)
value = strjoin(arrayfun(@(number) sprintf('%.8g', number), numbers, ...
    'UniformOutput', false), ', ');
end

function text = formatManualCases(cases)
if isempty(cases)
    text = '';
    return;
end
rows = compose('%.12g, %.12g', cases(:,1), cases(:,2));
text = char(strjoin(rows, '; '));
end

function value = iff(condition, trueValue, falseValue)
if condition
    value = trueValue;
else
    value = falseValue;
end
end
